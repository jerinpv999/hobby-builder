        a.ball(0.5 + sx * 0.083, 0.791, 1.751, 0.008, 0.017, 0.007, flat("#080605", 0.1), 8, 5)
        pointed_ear(a, (0.5 + sx * 0.105, 0.86, 1.57), (0.5 + sx * 0.15, 0.995, 1.56), 0.058, coat, "#d99a86")
        for k in range(4):
            a.tube((0.5 + sx * 0.055, 0.685 - k * 0.012, 1.8), (0.5 + sx * 0.23, 0.71 - k * 0.035, 1.78), 0.0025, 0.0008, flat("#f4efe4"), 5)
