def equine(a, coat, mane, zebra=False):
    s = Shape()
    s.ball((0.5, 1.04, 1.34), (0.2, 0.26, 0.5))
    s.ball((0.5, 1.07, 1.68), (0.215, 0.28, 0.27))
    s.ball((0.5, 1.12, 0.98), (0.215, 0.29, 0.3))
    s.limb(((0.5, 1.14, 1.72), 0.2), ((0.5, 1.5, 1.98), 0.135), ((0.5, 1.76, 2.12), 0.105))
    s.limb(((0.5, 1.76, 2.14), 0.13), ((0.5, 1.64, 2.32), 0.085), ((0.5, 1.51, 2.46), 0.062))
    for x in (-0.13, 0.13):
        leg(s, x, 1.74, 0.98, 0.09, (0.11, 0.056, 0.042), 0.03)
        leg(s, x, 0.9, 1.04, 0.09, (0.145, 0.062, 0.044), -0.11)

    def paint(p):
        if not zebra:
            return fur("#3b2415") if p[1] < 0.38 else fur(coat)
        if p[2] > 2.34 and p[1] < 1.66:
            return fur("#161313")
        wave = p[2] * 30 + math.sin(p[1] * 9) * 1.6 if p[1] > 0.72 else p[1] * 38
        if p[2] > 1.62 and p[1] > 1.2:
            wave = (p[2] + p[1]) * 24
        return fur("#141212") if math.sin(wave + noise(p, 3) * 1.5) > 0.12 else fur("#f2f0ea")

    skin(a, s, paint, 0.022, 9000 if zebra else 4600)
    hooves(a, [(x, z) for x in (-0.13, 0.13) for z in (1.74, 0.9)], 0.062)
    eye(a, 0.103, 1.74, 2.23, 0.03)
    nostrils(a, 0.036, 1.51, 2.515, 0.018)
    a.torus((0.5, 1.47, 2.46), 0.05, 0.006, flat("#2a1a14"), "y", 16, 6, 0.3, math.pi - 0.6)
    for sx in (-1, 1):
        pointed_ear(a, (0.5 + sx * 0.065, 1.84, 2.1), (0.5 + sx * 0.105, 2.08, 2.1), 0.045, coat if not zebra else "#f2f0ea", "#3a251c")
    neck = [(0.5, 1.86, 2.14), (0.5, 1.74, 1.96), (0.5, 1.52, 1.78), (0.5, 1.36, 1.62)]
    strands(a, neck, 0.016, mane, 46, 0.2 if not zebra else 0.09, 0.04, (0.0, -0.45 if not zebra else 0.8, -0.9 if not zebra else -0.4))
    strands(a, [(0.5, 1.9, 2.2), (0.5, 1.86, 2.16)], 0.012, mane, 12, 0.14, 0.035, (0.0, -0.4, 0.9))
    a.capsule((0.5, 1.22, 0.74), (0.5, 1.1, 0.58), 0.06, 0.035, fur(coat if not zebra else "#f2f0ea"), 12)
    strands(a, [(0.5, 1.13, 0.62), (0.5, 1.08, 0.56)], 0.018, mane, 38, 0.62, 0.08, (0.0, -1.0, -0.2))


