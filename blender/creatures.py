"""Animals and pets.  Bodies are fused into one smooth skin with Blender's voxel remesh,
then eyes, hooves, horns and other crisp details are added on top.  Stud units, facing +z."""
import math
import random

import mathutils
import mathutils.noise
from lib import *  # noqa: F403

DETAIL = {"k": 1.0}


def fur(colour):
    return flat(colour, 0.88)


def noise(p, f, offset=0.0):
    return mathutils.noise.noise(mathutils.Vector((p[0] * f + offset, p[1] * f, p[2] * f)))


class Shape:
    """Collects the soft parts of a body."""

    def __init__(self):
        self.a = Asset()

    def ball(self, c, r):
        r = r if isinstance(r, (tuple, list)) else (r, r, r)
        self.a.ball(*c, *r, "tyre_", 16, 10)

    def limb(self, *points):
        """A tapering chain of (position, radius)."""
        for (p, r0), (q, r1) in zip(points, points[1:]):
            self.a.capsule(p, q, r0, r1, "tyre_", 12)


def skin(a, s, paint, voxel=0.024, tris=4200, smooth=5):
    if "tyre_" not in MATS:
        ensure("tyre_", "#ffffff")
    blob(a, s.a, paint, voxel, int(tris * DETAIL["k"]), smooth)


def eye(a, x, y, z, r=0.032, cx=0.5, iris="#14100c"):
    for s in (-1, 1):
        a.ball(cx + s * x, y, z, r, r, r, flat(iris, 0.12), 12, 8)
        a.ball(cx + s * (x + r * 0.62), y + r * 0.35, z + r * 0.5, r * 0.28, r * 0.28, r * 0.28, flat("#ffffff", 0.2), 8, 5)


def nostrils(a, x, y, z, r=0.016, cx=0.5, colour="#1a1210"):
    for s in (-1, 1):
        a.ball(cx + s * x, y, z, r, r * 0.75, r * 0.6, flat(colour, 0.5), 8, 5)


def pointed_ear(a, base, tip, r, colour, inner=None):
    a.tube(base, tip, r, 0.006, fur(colour), 12)
    if inner:
        mid = tuple(base[i] + (tip[i] - base[i]) * 0.1 for i in range(3))
        a.tube((mid[0], mid[1], mid[2] + r * 0.45), (tip[0], tip[1] - r * 0.4, tip[2] + r * 0.12), r * 0.55, 0.004, fur(inner), 10)


def leg(s, x, z, hip, foot=0.07, r=(0.12, 0.07, 0.05), bend=0.05, cx=0.5):
    """Thigh, knee (or hock) and shin; `bend` moves the joint along z."""
    knee = hip * 0.5
    s.limb(((cx + x * 0.9, hip, z), r[0]), ((cx + x, knee, z + bend), r[1]), ((cx + x, foot + 0.06, z - bend * 0.3), r[2]), ((cx + x, foot, z), r[2] * 1.05))


def hooves(a, spots, r=0.06, colour="#1d1815", cx=0.5, h=0.1):
    for x, z in spots:
        a.tube((cx + x, 0.0, z + 0.01), (cx + x, h, z), r, r * 0.82, flat(colour, 0.55), 16)


def paws(a, spots, r, colour, cx=0.5):
    for x, z in spots:
        a.ball(cx + x, r * 0.62, z + r * 0.35, r, r * 0.65, r * 1.35, fur(colour), 14, 9)
        for k in (-1, 0, 1):
            a.ball(cx + x + k * r * 0.45, r * 0.35, z + r * 1.45, r * 0.26, r * 0.3, r * 0.3, fur(colour), 8, 5)


def strands(a, points, r, colour, count=26, length=0.22, spread=0.05, down=(0.0, -1.0, -0.35)):
    """Hair: many thin tapering locks along a line."""
    m = flat(colour, 0.8)
    for i in range(count):
        f = i / max(count - 1, 1) * (len(points) - 1)
        k = min(int(f), len(points) - 2)
        t = f - k
        p = tuple(points[k][j] + (points[k + 1][j] - points[k][j]) * t + random.uniform(-spread, spread) * 0.4 for j in range(3))
        mid = tuple(p[j] + down[j] * length * 0.5 + random.uniform(-spread, spread) for j in range(3))
        end = tuple(mid[j] + down[j] * length * 0.55 + random.uniform(-spread, spread) for j in range(3))
        a.tube(p, mid, r, r * 0.7, m, 6, caps=False)
        a.tube(mid, end, r * 0.7, 0.002, m, 6, caps=False)


